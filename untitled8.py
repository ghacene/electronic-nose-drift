# ================= ANALYZE TEMPORAL DRIFT =================
def analyze_drift_patterns(df, batch_col='batch'):
    """Analyze how features drift across batches"""
    print("\n📈 DRIFT ANALYSIS:")

    feature_cols = [c for c in df.columns if c.startswith('f')]
    batches = sorted(df[batch_col].unique())

    drift_stats = {}

    for feat in feature_cols[:16]:  # Analyze first 16 features as sample
        batch_means = []
        for b in batches:
            batch_data = df[df[batch_col] == b][feat]
            batch_means.append(batch_data.mean())

        # Calculate drift rate (linear trend)
        x = np.array(batches).reshape(-1, 1)
        y = np.array(batch_means)

        # Fit linear model to see drift direction
        from sklearn.linear_model import LinearRegression
        lr = LinearRegression()
        lr.fit(x, y)

        drift_stats[feat] = {
            'drift_rate': lr.coef_[0],
            'initial': batch_means[0],
            'final': batch_means[-1],
            'change_pct': (batch_means[-1] - batch_means[0]) / (abs(batch_means[0]) + 1e-6) * 100
        }

    # Show sample drift patterns
    print("\n  Sample drift patterns:")
    for feat in list(drift_stats.keys())[:5]:
        stats = drift_stats[feat]
        print(f"  {feat}: {stats['change_pct']:+.1f}% change, rate={stats['drift_rate']:+.2f}")

    return drift_stats

# Combine for analysis
combined = pd.concat([train, test], ignore_index=True)
drift_stats = analyze_drift_patterns(combined)

# ================= TEMPORAL FEATURE ENGINEERING =================
def sensor_features(s):
    start = (s-1)*8 + 1
    return [f"f{start+i}" for i in range(8)]

def create_temporal_features(df, drift_stats):
    """Create features that model temporal relationships"""
    df = df.copy()
    eps = 1e-6

    print("\n🔧 Engineering temporal features...")

    # 1. DRIFT COMPENSATION: Extrapolate batch 10 from batch 9 trend
    feature_cols = [c for c in df.columns if c.startswith('f')]

    # Calculate per-batch statistics
    for feat in feature_cols:
        # Batch-specific normalization
        batch_mean = df.groupby('batch')[feat].transform('mean')
        batch_std = df.groupby('batch')[feat].transform('std') + eps
        df[f'{feat}_norm'] = (df[feat] - batch_mean) / batch_std

        # Detrending: remove linear drift
        batch_medians = df.groupby('batch')[feat].median()
        batch_num = df['batch'].values

        # For each batch, calculate deviation from expected drift
        expected_drift = {}
        batches = sorted(df['batch'].unique())

        if len(batches) > 1:
            # Linear extrapolation
            x = np.array(batches)
            y = np.array([batch_medians[b] for b in batches])

            # Fit trend
            z = np.polyfit(x, y, deg=1)
            p = np.poly1d(z)

            # Detrended feature
            df[f'{feat}_detrend'] = df[feat] - p(batch_num)

    # 2. Physics-based ratios (invariant features)
    for s in range(1, 17):
        feats = sensor_features(s)

        # Key invariant ratios
        df[f'rise_ratio_{s}'] = df[feats[4]] / (np.abs(df[feats[2]]) + eps)
        df[f'decay_ratio_{s}'] = df[feats[7]] / (np.abs(df[feats[5]]) + eps)
        df[f'sens_norm_{s}'] = df[feats[0]] / (np.abs(df[feats[1]]) + eps)

        # Speed patterns
        df[f'rise_speed_{s}'] = (df[feats[4]] + df[feats[3]] + df[feats[2]]) / 3
        df[f'decay_speed_{s}'] = (df[feats[7]] + df[feats[6]] + df[feats[5]]) / 3
        df[f'speed_balance_{s}'] = df[f'rise_speed_{s}'] / (np.abs(df[f'decay_speed_{s}']) + eps)

        # Sensor aggregates
        df[f's{s}_mean'] = df[feats].mean(axis=1)
        df[f's{s}_std'] = df[feats].std(axis=1)
        df[f's{s}_range'] = df[feats].max(axis=1) - df[feats].min(axis=1)

    # 3. Cross-sensor patterns (gas signatures)
    for s1 in [1, 5, 9, 13]:  # Key sensors
        for s2 in [2, 6, 10, 14]:
            df[f'ratio_s{s1}_s{s2}'] = df[f's{s1}_mean'] / (np.abs(df[f's{s2}_mean']) + eps)

    # 4. Global statistics
    norm_cols = [c for c in df.columns if '_norm' in c]

    df['global_mean'] = df[norm_cols].mean(axis=1)
    df['global_std'] = df[norm_cols].std(axis=1)
    df['global_max'] = df[norm_cols].max(axis=1)
    df['global_min'] = df[norm_cols].min(axis=1)
    df['global_cv'] = df['global_std'] / (np.abs(df['global_mean']) + eps)

    # 5. Temporal features
    df['batch_norm'] = (df['batch'] - df['batch'].mean()) / (df['batch'].std() + eps)
    df['batch_squared'] = df['batch_norm'] ** 2
    df['time_decay'] = np.exp(-0.1 * df['batch'])

    print(f"  ✅ Total features: {df.shape[1]}")
    return df

# Create temporal features
