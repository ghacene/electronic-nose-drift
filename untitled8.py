# ================= TWO-STAGE TRAINING =================
print("\n🎯 Training temporal-aware ensemble...\n")

classes = np.sort(np.unique(y)) # classes will now be [0, 1, 2, 3, 4, 5]
n_classes = len(classes)

# Class weights
cls_counts = np.bincount(y) # np.bincount works with non-negative integers. If y has max 5, this will be of size 6.
# FIX: Adjust loop for class_weights to be 0-indexed
class_weights = {i: len(y)/(n_classes * cls_counts[i]) for i in range(n_classes)}
sample_weights = np.array([class_weights[label] for label in y])

# CV setup
gkf = GroupKFold(n_splits=N_SPLITS)
test_probs_lgb = np.zeros((len(X_test), n_classes))
test_probs_xgb = np.zeros((len(X_test), n_classes))
scores = []

for fold, (tr_idx, val_idx) in enumerate(gkf.split(X_train, y, train_batches)):
    print(f"Fold {fold+1}/{N_SPLITS}:")

    X_tr, X_val = X_train[tr_idx], X_train[val_idx]
    y_tr, y_val = y[tr_idx], y[val_idx]
    w_tr = sample_weights[tr_idx]

    # Model 1: LightGBM (fast, handles drift well)
    lgb_model = lgb.LGBMClassifier(
        n_estimators=2000,
        learning_rate=0.02,
        num_leaves=31,
        max_depth=8,
        min_child_samples=20,
        subsample=0.85,
        colsample_bytree=0.85,
        reg_alpha=0.1,
        reg_lambda=0.3,
        class_weight='balanced',
        random_state=42,
        verbose=-1
    )

    lgb_model.fit(
        X_tr, y_tr,
        sample_weight=w_tr,
        eval_set=[(X_val, y_val)],
        callbacks=[lgb.early_stopping(100, verbose=False)]
    )

    # Model 2: XGBoost (robust to temporal shifts)
    xgb_model = xgb.XGBClassifier(
        n_estimators=2000,
        learning_rate=0.02,
        max_depth=7,
        min_child_weight=3,
        subsample=0.85,
        colsample_bytree=0.85,
        reg_alpha=0.1,
        reg_lambda=0.5,
        random_state=42,
        eval_metric='mlogloss',
        early_stopping_rounds=100,
        tree_method='hist'
    )

    xgb_model.fit(
        X_tr, y_tr,
        sample_weight=w_tr,
        eval_set=[(X_val, y_val)],
        verbose=False
    )

    # Predictions
    lgb_val_probs = lgb_model.predict_proba(X_val)
    xgb_val_probs = xgb_model.predict_proba(X_val)

    # Ensemble validation predictions
    val_probs = 0.6 * lgb_val_probs + 0.4 * xgb_val_probs
    val_preds = classes[np.argmax(val_probs, axis=1)]

    score = f1_score(y_val, val_preds, average='macro')
    scores.append(score)

    print(f"  LightGBM iterations: {lgb_model.best_iteration_}")
    print(f"  XGBoost iterations: {xgb_model.best_iteration}")
    print(f"  Validation F1: {score:.5f}\n")

    # Accumulate test predictions
    test_probs_lgb += lgb_model.predict_proba(X_test) / N_SPLITS
    test_probs_xgb += xgb_model.predict_proba(X_test) / N_SPLITS

